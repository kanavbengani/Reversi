package cs3500.reversi.view;

/**
 * The {@code ViewType} enum represents different types of views for the Reversi game.
 * It defines two view types: SQUARE and HEX, which correspond to square and hexagonal
 * board representations, respectively.
 */
public enum ViewType {
  /**
   * Represents a square board view type.
   */
  SQUARE,
  
  /**
   * Represents a hexagonal board view type.
   */
  HEX;
}

